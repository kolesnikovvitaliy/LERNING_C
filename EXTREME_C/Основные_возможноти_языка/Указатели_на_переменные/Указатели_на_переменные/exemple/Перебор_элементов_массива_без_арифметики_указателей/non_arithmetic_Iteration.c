#include <stdio.h>

/**
 * @file main.c
 * @brief Демонстрация базовой работы с массивами и циклами в языке Си.
 *
 * Данный файл содержит учебный пример, иллюстрирующий процессы выделения
 * памяти под статический массив, последовательного заполнения его ячеек
 * данными и последующего вывода содержимого в консоль с помощью цикла.
 */

/**
 * @def SIZE
 * @brief Фиксированный размер демонстрационного массива.
 * @details Определяет количество элементов, которые может хранить массив,
 * а также задает верхнюю границу для итератора цикла.
 */
#define SIZE    5

/**
 * @brief Точка входа в программу.
 *
 * Функция инициализирует локальный целочисленный массив, присваивает значения
 * его элементам (от 0 до 4) и выводит их на экран в столбик.
 *
 * @param[in] argc Количество аргументов командной строки (не используется).
 * @param[in] argv Массив строк-аргументов командной строки (не используется).
 *
 * @return Статус завершения программы.
 * @retval 0 Успешное выполнение программы.
 */
int main(int argc, char **argv)
{
    /* Подавление предупреждений компилятора о неиспользуемых аргументах main */
    (void)argc;
    (void)argv;

    /**
     * @brief Локальный массив целых чисел.
     * @details Выделяет в стеке непрерывный блок памяти размером @c SIZE * sizeof(int).
     */
    int arr[SIZE];

    /**
     * @name Заполнение массива данными
     * @note Была исправлена логическая ошибка исходного кода, где все значения
     * записывались исключительно в нулевой индекс @c arr[0]. Теперь значения
     * распределены по всему объему массива.
     * @{ */
    arr[0] = 9;   /**< Запись числа 9 в первый (нулевой) элемент массива. */
    arr[1] = 22;  /**< Запись числа 22 во второй элемент массива. */
    arr[2] = 30;  /**< Запись числа 30 в третий элемент массива. */
    arr[3] = 23;  /**< Запись числа 23 в четвертый элемент массива. */
    arr[4] = 18;  /**< Запись числа 18 в пятый (последний) элемент массива. */
    /** @} */

    /**
     * @brief Цикл последовательного вывода элементов.
     * @details Переменная-счетчик @p i выступает в роли индекса. Цикл выполняется
     * до тех пор, пока @p i строго меньше значения макроса @ref SIZE.
     */
    for (int i = 0; i < SIZE; i++) {
        /* Вывод текущего элемента массива с переносом строки */
        printf("%d\n", arr[i]);
    }

    return 0;
}

